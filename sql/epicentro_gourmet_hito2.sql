-- ---------------------------------------------------------------------
-- CAJAS
--   Dias anteriores: CERRADA, con el total calculado desde los pedidos del dia.
--   Hoy: ABIERTA y en 0 para las unidades del festival activo (para probar Cerrar Caja).
-- ---------------------------------------------------------------------
INSERT INTO caja (fecha, unidad_venta_id, cajero_id, estado, monto_total)
SELECT p.fecha, p.unidad_venta_id, uvp.empleado_id, 'CERRADA', SUM(ip.cantidad * ip.precio_unitario)
FROM pedido p
JOIN item_pedido ip ON ip.pedido_id = p.id
JOIN unidad_venta_personal uvp ON uvp.unidad_venta_id = p.unidad_venta_id
JOIN cajero c ON c.id = uvp.empleado_id
WHERE p.fecha < CURDATE()
GROUP BY p.fecha, p.unidad_venta_id, uvp.empleado_id
ORDER BY p.fecha, p.unidad_venta_id;

INSERT INTO caja (fecha, unidad_venta_id, cajero_id, estado, monto_total)
SELECT CURDATE(), uvp.unidad_venta_id, uvp.empleado_id, 'ABIERTA', 0
FROM unidad_venta_personal uvp
JOIN cajero c ON c.id = uvp.empleado_id
JOIN unidad_venta uv ON uv.id = uvp.unidad_venta_id
WHERE uv.festival_id = 2
ORDER BY uvp.unidad_venta_id;

